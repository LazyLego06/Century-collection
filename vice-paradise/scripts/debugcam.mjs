import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:4173/');
await page.waitForSelector('#menu:not(.hidden)', { timeout: 120000 });
await page.click('#btn-play');
await page.evaluate(() => { const g = window.game; g.setState('playing'); g.input.enabled = true; g.env.hours = 12; g.settings.gfx.autoAdjust = false; });
await page.waitForTimeout(4000);
console.log(await page.evaluate(() => { const g = window.game; const d = new g.camera.position.constructor(); g.camera.getWorldDirection(d); return JSON.stringify({ cam: g.camera.position.toArray(), dir: d.toArray(), yaw: g.camYaw, pitch: g.camPitch, pl: g.player.pos.toArray() }); }));
await page.screenshot({ path: '/tmp/shots/d1.png' });
await browser.close();
